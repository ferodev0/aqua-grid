import React, {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useRef,
  useState,
} from "react";
import { deriveSensorStatus, evaluateNetworkAlerts } from "../simulation/alertRules";
import {
  createInitialAlerts,
  createInitialSensors,
  createInitialTelemetryHistory,
  DEFAULT_ALERT_THRESHOLDS,
  DEMO_MODE_LABEL,
  INITIAL_CHANNEL_SEGMENTS,
} from "../simulation/demoData";
import {
  calculateHydropowerEstimate,
  computeNetworkSummaryMetrics,
  runSimulationTick,
  SIMULATION_TICK_INTERVAL_MS,
  SimulationTickState,
} from "../simulation/simulationEngine";
import {
  AlertThresholds,
  AquaAlert,
  ChannelSegment,
  HydropowerEstimateInput,
  HydropowerEstimateResult,
  NetworkSummaryMetrics,
  Sensor,
  SensorStatus,
  TelemetryPoint,
  TelemetryTimeRange,
} from "../simulation/types";

export interface NewSensorInput {
  id?: string;
  name: string;
  channelSegmentId: string;
  location: {
    lat?: number;
    lng?: number;
    label: string;
  };
  baseline: {
    flowRateLps: number;
    waterLevelM: number;
  };
}

export interface SensorEditInput {
  name?: string;
  channelSegmentId?: string;
  location?: Partial<Sensor["location"]>;
  baseline?: Partial<Sensor["baseline"]>;
  status?: SensorStatus;
}

export interface NetworkContextValue {
  /** Persistent disclaimer banner text required by Spec Section 4 */
  demoBannerText: string;
  /** Shared list of simulated sensor stations */
  sensors: Sensor[];
  /** Illustrative channel segments connecting sensors */
  channelSegments: ChannelSegment[];
  /** Active and resolved alerts generated by simulation or system events */
  alerts: AquaAlert[];
  /** Rolling time-series history buffer for all sensors */
  telemetryHistory: TelemetryPoint[];
  /** Whether the downstream flow-reduction crisis scenario is currently active */
  isCrisisActive: boolean;
  /** Whether the periodic 2.5s simulation timer is running */
  isRunning: boolean;
  /** Configurable demonstration alert thresholds */
  thresholds: AlertThresholds;
  /** Derived network-wide summary metrics for Dashboard and Map headers */
  summaryMetrics: NetworkSummaryMetrics;
  /** Set of sensor IDs manually forced into offline state for demonstration */
  forcedOfflineSensorIds: string[];

  // Simulation & Scenario Controls
  triggerCrisis: () => void;
  resetSimulation: () => void;
  toggleCrisis: () => void;
  setSimulationRunning: (running: boolean) => void;
  stepOnce: () => void;
  updateThresholds: (updates: Partial<AlertThresholds>) => void;
  resolveAlert: (alertId: string) => void;
  toggleSensorOffline: (sensorId: string) => void;

  // Map Configuration & Prototype Editing Controls (Spec Section 7.2)
  addSensor: (input: NewSensorInput) => Sensor;
  updateSensor: (sensorId: string, updates: SensorEditInput) => void;
  removeSensor: (sensorId: string) => void;
  addChannelSegment: (
    input: Omit<ChannelSegment, "id" | "isIllustrative"> & { id?: string }
  ) => ChannelSegment;
  updateChannelSegment: (
    segmentId: string,
    updates: Partial<ChannelSegment>
  ) => void;
  removeChannelSegment: (segmentId: string) => void;

  // Selectors & Calculators
  getSensorById: (sensorId: string) => Sensor | undefined;
  getSensorTelemetry: (
    sensorId: string,
    range?: TelemetryTimeRange
  ) => TelemetryPoint[];
  getSensorAlerts: (sensorId: string) => AquaAlert[];
  estimateHydropower: (
    input: HydropowerEstimateInput
  ) => HydropowerEstimateResult;
}

const NetworkContext = createContext<NetworkContextValue | undefined>(undefined);

function createInitialSimulationState(): SimulationTickState {
  const nowMs = Date.now();
  const nowIso = new Date(nowMs).toISOString();
  const sensors = createInitialSensors(nowIso);
  const telemetryHistory = createInitialTelemetryHistory(sensors, 36, 5 * 60 * 1000, nowMs);
  const alerts = createInitialAlerts(nowIso);

  return {
    sensors,
    channelSegments: INITIAL_CHANNEL_SEGMENTS.map((seg) => ({
      ...seg,
      path: seg.path.map((pt) => ({ ...pt })),
    })),
    alerts,
    telemetryHistory,
  };
}

export const NetworkProvider: React.FC<{ children: React.ReactNode }> = ({
  children,
}) => {
  const [simState, setSimState] = useState<SimulationTickState>(() =>
    createInitialSimulationState()
  );
  const [isCrisisActive, setIsCrisisActive] = useState<boolean>(false);
  const [isRunning, setIsRunning] = useState<boolean>(true);
  const [thresholds, setThresholds] = useState<AlertThresholds>(
    DEFAULT_ALERT_THRESHOLDS
  );
  const [forcedOfflineIds, setForcedOfflineIds] = useState<Set<string>>(
    () => new Set()
  );

  // Refs for interval callback access without resetting the timer unnecessarily
  const isCrisisRef = useRef(isCrisisActive);
  isCrisisRef.current = isCrisisActive;

  const thresholdsRef = useRef(thresholds);
  thresholdsRef.current = thresholds;

  const forcedOfflineRef = useRef(forcedOfflineIds);
  forcedOfflineRef.current = forcedOfflineIds;

  const stepOnce = useCallback(() => {
    setSimState((prev) =>
      runSimulationTick(
        prev,
        thresholdsRef.current,
        isCrisisRef.current,
        forcedOfflineRef.current,
        Date.now()
      )
    );
  }, []);

  useEffect(() => {
    if (!isRunning) {
      return;
    }
    const timer = window.setInterval(() => {
      stepOnce();
    }, SIMULATION_TICK_INTERVAL_MS);

    return () => window.clearInterval(timer);
  }, [isRunning, stepOnce]);

  const triggerCrisis = useCallback(() => {
    const nowMs = Date.now();
    const nowIso = new Date(nowMs).toISOString();
    isCrisisRef.current = true;
    setIsCrisisActive(true);

    setSimState((prev) => {
      const crisisEventAlert: AquaAlert = {
        id: `ALT-SYS-CRISIS-${nowMs}`,
        severity: "critical",
        title: "Crisis Simulation Activated — Unexpected Downstream Flow Reduction",
        message:
          "Simulated downstream reduction triggered across Village Approach (S03) and Lower Channel (S04). Upstream stations S01 and S02 remain near baseline. Field inspection of sections SEG-03 and SEG-04 is recommended.",
        sensorIds: ["S03", "S04"],
        channelSegmentId: "SEG-03",
        createdAt: nowIso,
        status: "active",
        source: "simulation",
      };

      const withoutOldCrisisBanner = prev.alerts.filter(
        (a) => !a.id.startsWith("ALT-SYS-CRISIS-")
      );

      const nextState = runSimulationTick(
        {
          ...prev,
          alerts: [crisisEventAlert, ...withoutOldCrisisBanner],
        },
        thresholdsRef.current,
        true,
        forcedOfflineRef.current,
        nowMs
      );

      return nextState;
    });
  }, []);

  const resetSimulation = useCallback(() => {
    const nowMs = Date.now();
    const nowIso = new Date(nowMs).toISOString();
    isCrisisRef.current = false;
    setIsCrisisActive(false);

    const emptyOffline = new Set<string>();
    forcedOfflineRef.current = emptyOffline;
    setForcedOfflineIds(emptyOffline);

    const freshState = createInitialSimulationState();
    const resetNotice: AquaAlert = {
      id: `ALT-SYS-RESET-${nowMs}`,
      severity: "info",
      title: "Simulation Reset to Normal Baseline",
      message:
        "Flow at S03 and S04 returned to normal simulated operating range. Scenario alerts have been cleared.",
      sensorIds: ["S01", "S02", "S03", "S04"],
      createdAt: nowIso,
      status: "active",
      source: "system",
    };

    setSimState({
      ...freshState,
      alerts: [resetNotice, ...freshState.alerts],
    });
  }, []);

  const toggleCrisis = useCallback(() => {
    if (isCrisisRef.current) {
      resetSimulation();
    } else {
      triggerCrisis();
    }
  }, [resetSimulation, triggerCrisis]);

  const setSimulationRunning = useCallback((running: boolean) => {
    setIsRunning(running);
  }, []);

  const updateThresholds = useCallback((updates: Partial<AlertThresholds>) => {
    setThresholds((prev) => {
      const next = { ...prev, ...updates };
      thresholdsRef.current = next;

      setSimState((currState) => {
        const nowMs = Date.now();
        const nowIso = new Date(nowMs).toISOString();
        const updatedSensors = currState.sensors.map((s) => ({
          ...s,
          status: deriveSensorStatus(
            s,
            next,
            nowMs,
            forcedOfflineRef.current.has(s.id)
          ),
        }));
        const updatedAlerts = evaluateNetworkAlerts(
          updatedSensors,
          currState.channelSegments,
          currState.alerts,
          next,
          nowIso
        );
        return {
          ...currState,
          sensors: updatedSensors,
          alerts: updatedAlerts,
        };
      });

      return next;
    });
  }, []);

  const resolveAlert = useCallback((alertId: string) => {
    setSimState((prev) => ({
      ...prev,
      alerts: prev.alerts.map((a) =>
        a.id === alertId ? { ...a, status: "resolved" } : a
      ),
    }));
  }, []);

  const toggleSensorOffline = useCallback((sensorId: string) => {
    setForcedOfflineIds((prev) => {
      const next = new Set(prev);
      const willBeOffline = !next.has(sensorId);
      if (willBeOffline) {
        next.add(sensorId);
      } else {
        next.delete(sensorId);
      }
      forcedOfflineRef.current = next;

      const nowMs = Date.now();
      const nowIso = new Date(nowMs).toISOString();
      setSimState((curr) => {
        const updatedSensors = curr.sensors.map((s) =>
          s.id === sensorId
            ? {
                ...s,
                status: deriveSensorStatus(
                  s,
                  thresholdsRef.current,
                  nowMs,
                  willBeOffline
                ),
                current: willBeOffline
                  ? s.current
                  : { ...s.current, updatedAt: nowIso },
              }
            : s
        );
        const updatedAlerts = evaluateNetworkAlerts(
          updatedSensors,
          curr.channelSegments,
          curr.alerts,
          thresholdsRef.current,
          nowIso
        );
        return {
          ...curr,
          sensors: updatedSensors,
          alerts: updatedAlerts,
        };
      });

      return next;
    });
  }, []);

  // Map Editing Actions (Prototype State Only)
  const addSensor = useCallback((input: NewSensorInput): Sensor => {
    const nowIso = new Date().toISOString();
    const generatedId =
      input.id?.trim() ||
      `S0${Math.max(5, Math.floor(Math.random() * 90 + 10))}`;

    const newSensor: Sensor = {
      id: generatedId,
      name: input.name.trim() || `Demo Station ${generatedId}`,
      channelSegmentId: input.channelSegmentId || "SEG-01",
      location: {
        lat: input.location.lat ?? 35.114,
        lng: input.location.lng ?? 32.852,
        label: input.location.label || "Illustrative Demonstration Point",
        isIllustrative: true,
      },
      baseline: {
        flowRateLps: Number(input.baseline.flowRateLps) || 8.0,
        waterLevelM: Number(input.baseline.waterLevelM) || 0.3,
      },
      current: {
        flowRateLps: Number(input.baseline.flowRateLps) || 8.0,
        waterLevelM: Number(input.baseline.waterLevelM) || 0.3,
        flowVelocityMps: 0.7,
        batteryPercent: 100,
        signalPercent: 95,
        updatedAt: nowIso,
      },
      status: "normal",
    };

    setSimState((prev) => {
      const initialPoints = createInitialTelemetryHistory([newSensor], 18);
      return {
        ...prev,
        sensors: [...prev.sensors, newSensor],
        telemetryHistory: [...prev.telemetryHistory, ...initialPoints],
      };
    });

    return newSensor;
  }, []);

  const updateSensor = useCallback(
    (sensorId: string, updates: SensorEditInput) => {
      setSimState((prev) => {
        const nowMs = Date.now();
        const nowIso = new Date(nowMs).toISOString();
        const nextSensors = prev.sensors.map((sensor) => {
          if (sensor.id !== sensorId) {
            return sensor;
          }
          const nextBaseline = updates.baseline
            ? { ...sensor.baseline, ...updates.baseline }
            : sensor.baseline;
          const nextLocation = updates.location
            ? {
                ...sensor.location,
                ...updates.location,
                isIllustrative: true,
              }
            : sensor.location;

          const updated: Sensor = {
            ...sensor,
            name: updates.name !== undefined ? updates.name : sensor.name,
            channelSegmentId:
              updates.channelSegmentId !== undefined
                ? updates.channelSegmentId
                : sensor.channelSegmentId,
            location: nextLocation,
            baseline: nextBaseline,
            status: updates.status ?? sensor.status,
          };

          if (!updates.status) {
            updated.status = deriveSensorStatus(
              updated,
              thresholdsRef.current,
              nowMs,
              forcedOfflineRef.current.has(sensor.id)
            );
          }
          return updated;
        });

        const nextAlerts = evaluateNetworkAlerts(
          nextSensors,
          prev.channelSegments,
          prev.alerts,
          thresholdsRef.current,
          nowIso
        );

        return {
          ...prev,
          sensors: nextSensors,
          alerts: nextAlerts,
        };
      });
    },
    []
  );

  const removeSensor = useCallback((sensorId: string) => {
    setSimState((prev) => ({
      ...prev,
      sensors: prev.sensors.filter((s) => s.id !== sensorId),
      telemetryHistory: prev.telemetryHistory.filter(
        (pt) => pt.sensorId !== sensorId
      ),
    }));
  }, []);

  const addChannelSegment = useCallback(
    (
      input: Omit<ChannelSegment, "id" | "isIllustrative"> & { id?: string }
    ): ChannelSegment => {
      const newSegment: ChannelSegment = {
        id:
          input.id?.trim() ||
          `SEG-0${Math.max(5, Math.floor(Math.random() * 90 + 10))}`,
        name: input.name,
        upstreamSensorId: input.upstreamSensorId,
        downstreamSensorId: input.downstreamSensorId,
        path: input.path,
        isIllustrative: true,
      };

      setSimState((prev) => ({
        ...prev,
        channelSegments: [...prev.channelSegments, newSegment],
      }));

      return newSegment;
    },
    []
  );

  const updateChannelSegment = useCallback(
    (segmentId: string, updates: Partial<ChannelSegment>) => {
      setSimState((prev) => ({
        ...prev,
        channelSegments: prev.channelSegments.map((seg) =>
          seg.id === segmentId
            ? { ...seg, ...updates, isIllustrative: true }
            : seg
        ),
      }));
    },
    []
  );

  const removeChannelSegment = useCallback((segmentId: string) => {
    setSimState((prev) => ({
      ...prev,
      channelSegments: prev.channelSegments.filter(
        (seg) => seg.id !== segmentId
      ),
    }));
  }, []);

  // Selectors
  const getSensorById = useCallback(
    (sensorId: string): Sensor | undefined =>
      simState.sensors.find(
        (s) => s.id.toLowerCase() === sensorId.toLowerCase()
      ),
    [simState.sensors]
  );

  const getSensorTelemetry = useCallback(
    (
      sensorId: string,
      range: TelemetryTimeRange = "1h"
    ): TelemetryPoint[] => {
      const allForSensor = simState.telemetryHistory.filter(
        (pt) => pt.sensorId.toLowerCase() === sensorId.toLowerCase()
      );

      // Slice appropriate point density for the selected time range view
      const maxPointsByRange: Record<TelemetryTimeRange, number> = {
        "1h": 24,
        "24h": 48,
        "7d": 96,
      };
      const limit = maxPointsByRange[range] ?? 24;
      return allForSensor.slice(-limit);
    },
    [simState.telemetryHistory]
  );

  const getSensorAlerts = useCallback(
    (sensorId: string): AquaAlert[] =>
      simState.alerts.filter((alert) =>
        alert.sensorIds.some(
          (id) => id.toLowerCase() === sensorId.toLowerCase()
        )
      ),
    [simState.alerts]
  );

  const summaryMetrics = useMemo(
    () => computeNetworkSummaryMetrics(simState.sensors, simState.alerts),
    [simState.sensors, simState.alerts]
  );

  const forcedOfflineSensorIds = useMemo(
    () => Array.from(forcedOfflineIds),
    [forcedOfflineIds]
  );

  const contextValue = useMemo<NetworkContextValue>(
    () => ({
      demoBannerText: DEMO_MODE_LABEL,
      sensors: simState.sensors,
      channelSegments: simState.channelSegments,
      alerts: simState.alerts,
      telemetryHistory: simState.telemetryHistory,
      isCrisisActive,
      isRunning,
      thresholds,
      summaryMetrics,
      forcedOfflineSensorIds,
      triggerCrisis,
      resetSimulation,
      toggleCrisis,
      setSimulationRunning,
      stepOnce,
      updateThresholds,
      resolveAlert,
      toggleSensorOffline,
      addSensor,
      updateSensor,
      removeSensor,
      addChannelSegment,
      updateChannelSegment,
      removeChannelSegment,
      getSensorById,
      getSensorTelemetry,
      getSensorAlerts,
      estimateHydropower: calculateHydropowerEstimate,
    }),
    [
      simState.sensors,
      simState.channelSegments,
      simState.alerts,
      simState.telemetryHistory,
      isCrisisActive,
      isRunning,
      thresholds,
      summaryMetrics,
      forcedOfflineSensorIds,
      triggerCrisis,
      resetSimulation,
      toggleCrisis,
      setSimulationRunning,
      stepOnce,
      updateThresholds,
      resolveAlert,
      toggleSensorOffline,
      addSensor,
      updateSensor,
      removeSensor,
      addChannelSegment,
      updateChannelSegment,
      removeChannelSegment,
      getSensorById,
      getSensorTelemetry,
      getSensorAlerts,
    ]
  );

  return (
    <NetworkContext.Provider value={contextValue}>
      {children}
    </NetworkContext.Provider>
  );
};

/**
 * Primary hook for consuming the shared Aqua Grid simulation state and controls.
 */
export function useNetwork(): NetworkContextValue {
  const context = useContext(NetworkContext);
  if (!context) {
    throw new Error("useNetwork must be used within a <NetworkProvider>");
  }
  return context;
}

/**
 * Alias for useNetwork so page components using either naming convention work seamlessly.
 */
export const useSimulation = useNetwork;
